-- Vagas da eliminatoria de um torneio de grupos (`montarFaseEliminatoria`):
-- os 1os colocados nas vagas dos cabecas (1A = 1, 1B = 2...); cada um dos
-- demais vai para a vaga livre mais longe de quem e do mesmo grupo.
create function privado.vagas_da_fase_eliminatoria(p_torneio_id text, p_classificados integer)
returns text[]
language plpgsql
stable
set search_path = ''
as $$
declare
  v_letras text[];
  v_classificados jsonb := '[]';
  v_lista jsonb;
  v_total integer := 0;
  v_ordem integer[];
  v_vagas text[];
  v_grupo_da_vaga integer[];
  v_proximo integer := 1;
  v_colocacoes integer := 0;
  v_grupos integer[];
  v_candidatas integer[];
  v_escolhida integer;
  v_mais_tarde integer;
  v_encontro integer;
  v_g integer;
  v_vaga integer;
begin
  select array_agg(distinct i.grupo order by i.grupo) into v_letras
    from public.torneio_inscritos i
   where i.torneio_id = p_torneio_id and i.grupo is not null;

  for v_g in 1..coalesce(cardinality(v_letras), 0) loop
    select coalesce(jsonb_agg(c.inscricao_id order by c.posicao), '[]') into v_lista
      from privado.classificar(p_torneio_id, v_letras[v_g]) as c
     where c.posicao <= least(greatest(p_classificados, 1),
             (select count(*) from public.torneio_inscritos i
               where i.torneio_id = p_torneio_id and i.grupo = v_letras[v_g]));
    v_classificados := v_classificados || jsonb_build_array(v_lista);
    v_total := v_total + jsonb_array_length(v_lista);
    v_colocacoes := greatest(v_colocacoes, jsonb_array_length(v_lista));
  end loop;

  v_ordem := privado.ordem_dos_cabecas(privado.tamanho_da_chave(v_total));
  v_vagas := array_fill(null::text, array[cardinality(v_ordem)]);
  v_grupo_da_vaga := array_fill(null::integer, array[cardinality(v_ordem)]);

  for v_colocacao in 0..v_colocacoes - 1 loop
    -- Grupos (contados a partir de 0) que tem alguem nessa colocacao.
    select coalesce(array_agg(g.n - 1 order by g.n), '{}') into v_grupos
      from jsonb_array_elements(v_classificados) with ordinality as g(lista, n)
     where jsonb_array_length(g.lista) > v_colocacao;
    v_candidatas := '{}';
    for v_i in 0..cardinality(v_grupos) - 1 loop
      v_candidatas := v_candidatas || (array_position(v_ordem, v_proximo + v_i) - 1);
    end loop;
    v_proximo := v_proximo + cardinality(v_grupos);

    foreach v_g in array v_grupos loop
      v_escolhida := -1;
      v_mais_tarde := -1;
      foreach v_vaga in array v_candidatas loop
        continue when v_vagas[v_vaga + 1] is not null;
        -- Sem ninguem do grupo na chave ainda: "infinito".
        select coalesce(min(privado.rodada_do_encontro(v_vaga, o.n::int - 1)), 1000)
          into v_encontro
          from unnest(v_grupo_da_vaga) with ordinality as o(grupo, n)
         where o.grupo = v_g;
        if v_encontro > v_mais_tarde then
          v_escolhida := v_vaga;
          v_mais_tarde := v_encontro;
        end if;
      end loop;
      v_vagas[v_escolhida + 1] := v_classificados -> v_g ->> v_colocacao;
      v_grupo_da_vaga[v_escolhida + 1] := v_g;
    end loop;
  end loop;

  return v_vagas;
end;
$$;

-- Depois de mudar um resultado de grupo (`atualizarFaseEliminatoria`): se os
-- grupos terminaram, monta (ou remonta) a eliminatoria; se nao terminaram,
-- tira a que existir. Se a chave remontada for igual a atual, nada muda.
create function privado.atualizar_fase_eliminatoria(p_torneio_id text)
returns void
language plpgsql
set search_path = ''
as $$
declare
  v_torneio public.torneios;
  v_classificados integer;
  v_nova public.partidas[];
  v_assinatura_atual text;
  v_assinatura_nova text;
begin
  select * into v_torneio from public.torneios where id = p_torneio_id;
  if v_torneio.formato <> 'grupos_eliminatoria' then
    return;
  end if;
  if exists (select 1 from public.partidas p
              where p.torneio_id = p_torneio_id and p.grupo is null and p.vencedor is not null) then
    perform privado.recusar(
      'A fase eliminatória já começou: os resultados dos grupos não podem mais ser mudados.');
  end if;

  if not exists (select 1 from public.partidas p
                  where p.torneio_id = p_torneio_id and p.grupo is not null)
     or exists (select 1 from public.partidas p
                 where p.torneio_id = p_torneio_id and p.grupo is not null and p.vencedor is null) then
    delete from public.partidas p where p.torneio_id = p_torneio_id and p.grupo is null;
    return;
  end if;

  select c.classificados_por_grupo into v_classificados from public.configuracoes c where c.id = 1;
  v_nova := array(
    select l from privado.linhas_da_eliminatoria(
      v_torneio,
      privado.vagas_da_fase_eliminatoria(p_torneio_id, v_classificados),
      'pt-' || replace(gen_random_uuid()::text, '-', '')) as l);

  select string_agg(format('%s|%s|%s|%s', p.rodada, p.ordem,
           coalesce(p.inscricao_a_id, ''), coalesce(p.inscricao_b_id, '')), ';'
           order by p.rodada, p.ordem)
    into v_assinatura_atual
    from public.partidas p where p.torneio_id = p_torneio_id and p.grupo is null;
  select string_agg(format('%s|%s|%s|%s', p.rodada, p.ordem,
           coalesce(p.inscricao_a_id, ''), coalesce(p.inscricao_b_id, '')), ';'
           order by p.rodada, p.ordem)
    into v_assinatura_nova
    from unnest(v_nova) as p;
  if v_assinatura_atual = v_assinatura_nova then
    return;
  end if;

  delete from public.partidas p where p.torneio_id = p_torneio_id and p.grupo is null;
  insert into public.partidas select * from unnest(v_nova);
end;
$$;

-- Situacao pelo andamento (`torneioTerminou`): eliminatoria = final decidida;
-- todos contra todos = todas as partidas jogadas. Devolve a situacao.
create function privado.atualizar_situacao_do_torneio(p_torneio_id text)
returns text
language plpgsql
set search_path = ''
as $$
declare
  v_formato text;
  v_terminou boolean;
  v_situacao text;
begin
  select t.formato into v_formato from public.torneios t where t.id = p_torneio_id;
  if v_formato = 'todos_contra_todos' then
    v_terminou :=
      exists (select 1 from public.partidas p where p.torneio_id = p_torneio_id)
      and not exists (select 1 from public.partidas p
                       where p.torneio_id = p_torneio_id and p.vencedor is null);
  else
    v_terminou := exists (
      select 1 from public.partidas p
       where p.torneio_id = p_torneio_id and p.grupo is null
         and p.proxima_partida_id is null and p.vencedor is not null);
  end if;
  v_situacao := case when v_terminou then 'encerrado' else 'em_andamento' end;
  update public.torneios t set situacao = v_situacao
   where t.id = p_torneio_id and t.situacao <> v_situacao;
  return v_situacao;
end;
$$;

-- Por que o resultado desta partida nao pode mais ser mudado (null = pode).
-- Eliminatoria: a partida seguinte ja foi jogada. Grupos: a eliminatoria ja
-- comecou (`bloqueioDeCorrecao`).
create function privado.bloqueio_de_correcao(p_partida public.partidas)
returns text
language plpgsql
stable
set search_path = ''
as $$
declare
  v_seguinte public.partidas;
begin
  if p_partida.grupo is not null then
    if exists (select 1 from public.partidas p
                where p.torneio_id = p_partida.torneio_id and p.grupo is null and p.vencedor is not null) then
      return 'A fase eliminatória já começou: os resultados dos grupos não podem mais ser mudados.';
    end if;
    return null;
  end if;
  if p_partida.vencedor is null or p_partida.proxima_partida_id is null then
    return null;
  end if;
  select * into v_seguinte from public.partidas p where p.id = p_partida.proxima_partida_id;
  if v_seguinte.vencedor is not null then
    return format('A partida seguinte (%s) já foi jogada: este resultado não pode mais ser mudado.',
      coalesce(v_seguinte.fase, 'próxima rodada'));
  end if;
  return null;
end;
$$;

