-- Cria o torneio com as inscricoes ([{alunosIds: [...], cabecaDeChave: 1}]).
-- Devolve o id do torneio.
create function public.criar_torneio(
  p_nome text, p_data date, p_formato text, p_duplas boolean,
  p_inscricoes jsonb default '[]', p_categoria text default null)
returns text
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_id text;
begin
  perform privado.iniciar_operacao('Criar torneio', 'ranking');
  perform privado.validar_dados_do_torneio(p_nome, p_data, p_formato);
  perform privado.validar_inscricoes(coalesce(p_duplas, false), p_inscricoes);

  insert into public.torneios (nome, data, formato, categoria, duplas, situacao)
  values (btrim(p_nome), p_data, p_formato, nullif(p_categoria, ''), coalesce(p_duplas, false), 'inscricoes')
  returning id into v_id;

  insert into public.torneio_inscritos (torneio_id, alunos_ids, cabeca_de_chave)
  select v_id,
         array(select jsonb_array_elements_text(i -> 'alunosIds')),
         (i ->> 'cabecaDeChave')::smallint
    from jsonb_array_elements(coalesce(p_inscricoes, '[]')) with ordinality as e(i, n)
   order by n;
  return v_id;
