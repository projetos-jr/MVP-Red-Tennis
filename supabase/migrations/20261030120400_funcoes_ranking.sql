-- Edita nome, data e categoria a qualquer momento. Formato, simples/duplas e
-- inscricoes so mudam enquanto a chave nao foi gerada. `p_inscricoes` null =
-- nao mexe nas inscricoes; com lista, a lista passa a ser as inscricoes
-- (as com `id` existente sao mantidas; as sem `id` sao novas). Devolve o id.
create function public.editar_torneio(
  p_id text, p_nome text, p_data date, p_formato text, p_duplas boolean,
  p_categoria text default null, p_inscricoes jsonb default null)
returns text
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_torneio public.torneios;
  v_atuais jsonb;
  v_inscricao jsonb;
  v_alunos text[];
  v_cabeca smallint;
begin
  perform privado.iniciar_operacao('Editar torneio', 'ranking');
  select * into v_torneio from public.torneios t where t.id = p_id for update;
  if not found then
    perform privado.recusar('Torneio não encontrado.');
  end if;
  perform privado.validar_dados_do_torneio(p_nome, p_data, p_formato);
  if v_torneio.situacao <> 'inscricoes'
     and (p_formato <> v_torneio.formato
          or coalesce(p_duplas, false) <> v_torneio.duplas
          or p_inscricoes is not null) then
    perform privado.recusar(
      'A chave já foi gerada: para mudar formato ou inscrições, desfaça a chave primeiro.');
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'id', i.id, 'alunosIds', to_jsonb(i.alunos_ids), 'cabecaDeChave', i.cabeca_de_chave)
           order by i.ordem_inscricao), '[]')
    into v_atuais
    from public.torneio_inscritos i where i.torneio_id = p_id;
  perform privado.validar_inscricoes(coalesce(p_duplas, false), coalesce(p_inscricoes, v_atuais));

  update public.torneios t
     set nome = btrim(p_nome), data = p_data, formato = p_formato,
         categoria = nullif(p_categoria, ''), duplas = coalesce(p_duplas, false)
   where t.id = p_id;

  if p_inscricoes is not null then
    delete from public.torneio_inscritos i
     where i.torneio_id = p_id
       and i.id not in (select e.i ->> 'id' from jsonb_array_elements(p_inscricoes) as e(i)
                         where e.i ->> 'id' is not null);
    for v_inscricao in
      select e.i from jsonb_array_elements(p_inscricoes) with ordinality as e(i, n) order by e.n
    loop
      v_alunos := array(select jsonb_array_elements_text(v_inscricao -> 'alunosIds'));
      v_cabeca := (v_inscricao ->> 'cabecaDeChave')::smallint;
      if exists (select 1 from public.torneio_inscritos i
                  where i.id = v_inscricao ->> 'id' and i.torneio_id = p_id) then
        update public.torneio_inscritos i
           set alunos_ids = v_alunos, cabeca_de_chave = v_cabeca
         where i.id = v_inscricao ->> 'id';
      else
        insert into public.torneio_inscritos (torneio_id, alunos_ids, cabeca_de_chave)
        values (p_id, v_alunos, v_cabeca);
      end if;
    end loop;
  end if;
  return p_id;
end;
$$;

-- Gera a chave e poe o torneio "em andamento". Quem nao e cabeca de chave e
-- sorteado: pela ordem de `p_sorteio` (ids das inscricoes, na ordem sorteada
-- pela tela) ou, sem ela, pelo banco. No formato de grupos, gera so os jogos
-- dos grupos: a eliminatoria e montada quando eles terminam. Devolve o id.
create function public.gerar_chave_do_torneio(p_id text, p_sorteio text[] default null)
returns text
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_torneio public.torneios;
  v_classificados integer;
  v_ordem text[];
  v_vagas text[];
  v_tamanhos integer[];
  v_contagem integer[];
  v_grupo_de integer[];
  v_atual integer := 0;
  v_sentido integer := 1;
  v_prefixo text := 'pt-' || replace(gen_random_uuid()::text, '-', '');
  v_g integer;
begin
  perform privado.iniciar_operacao('Gerar chave do torneio', 'ranking');
  select * into v_torneio from public.torneios t where t.id = p_id for update;
  if not found then
    perform privado.recusar('Torneio não encontrado.');
  end if;
  if v_torneio.situacao <> 'inscricoes' then
    perform privado.recusar('A chave deste torneio já foi gerada.');
  end if;

  if p_sorteio is not null and (
       exists (select 1 from unnest(p_sorteio) as s(id)
                where not exists (select 1 from public.torneio_inscritos i
                                   where i.id = s.id and i.torneio_id = p_id))
       or exists (select 1 from public.torneio_inscritos i
                   where i.torneio_id = p_id and i.cabeca_de_chave is null
                     and coalesce(array_length(array_positions(p_sorteio, i.id), 1), 0) <> 1)) then
    perform privado.recusar('O sorteio precisa trazer cada inscrição do torneio uma vez.');
  end if;

  -- Cabecas de chave pelo numero; depois os demais, na ordem do sorteio.
  select array_agg(i.id order by
           i.cabeca_de_chave nulls last,
           case when p_sorteio is null then random()
                else array_position(p_sorteio, i.id)::double precision end)
    into v_ordem
    from public.torneio_inscritos i where i.torneio_id = p_id;
  select c.classificados_por_grupo into v_classificados from public.configuracoes c where c.id = 1;
  perform privado.validar_previa_da_chave(
    v_torneio.formato, coalesce(cardinality(v_ordem), 0), v_classificados);

  if v_torneio.formato = 'eliminatoria' then
    select array_agg(v_ordem[n] order by v) into v_vagas
      from unnest(privado.ordem_dos_cabecas(privado.tamanho_da_chave(cardinality(v_ordem))))
           with ordinality as o(n, v);
    insert into public.partidas
    select * from privado.linhas_da_eliminatoria(v_torneio, v_vagas, v_prefixo);

  elsif v_torneio.formato = 'todos_contra_todos' then
    insert into public.partidas
    select * from privado.linhas_todos_contra_todos(v_torneio, v_ordem, v_prefixo, null);

  else
    -- Grupos em "serpentina" (A B | B A | A B...): cabecas em grupos diferentes.
    v_tamanhos := privado.tamanhos_dos_grupos(cardinality(v_ordem));
    v_contagem := array_fill(0, array[cardinality(v_tamanhos)]);
    v_grupo_de := '{}';
    for v_i in 1..cardinality(v_ordem) loop
      while v_contagem[v_atual + 1] >= v_tamanhos[v_atual + 1] loop
        -- avancar (na ponta, inverte o sentido e repete o mesmo grupo)
        if v_atual + v_sentido < 0 or v_atual + v_sentido >= cardinality(v_tamanhos) then
          v_sentido := -v_sentido;
        else
          v_atual := v_atual + v_sentido;
        end if;
      end loop;
      v_grupo_de := v_grupo_de || v_atual;
      v_contagem[v_atual + 1] := v_contagem[v_atual + 1] + 1;
      if v_atual + v_sentido < 0 or v_atual + v_sentido >= cardinality(v_tamanhos) then
        v_sentido := -v_sentido;
      else
        v_atual := v_atual + v_sentido;
      end if;
    end loop;

    update public.torneio_inscritos i
       set grupo = chr(65 + v_grupo_de[array_position(v_ordem, i.id)])
     where i.torneio_id = p_id;

    for v_g in 0..cardinality(v_tamanhos) - 1 loop
      insert into public.partidas
      select * from privado.linhas_todos_contra_todos(
        v_torneio,
        array(select v_ordem[n] from generate_series(1, cardinality(v_ordem)) as n
               where v_grupo_de[n] = v_g order by n),
        v_prefixo,
        chr(65 + v_g));
    end loop;
  end if;

  update public.torneios t set situacao = 'em_andamento' where t.id = p_id;
  return p_id;
end;
$$;

-- Apaga a chave (so sem nenhum resultado) e reabre as inscricoes. Devolve o id.
create function public.desfazer_chave_do_torneio(p_id text)
returns text
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_torneio public.torneios;
begin
  perform privado.iniciar_operacao('Desfazer chave do torneio', 'ranking');
  select * into v_torneio from public.torneios t where t.id = p_id for update;
  if not found then
    perform privado.recusar('Torneio não encontrado.');
  end if;
  if v_torneio.situacao = 'inscricoes' then
    perform privado.recusar('Este torneio ainda não tem chave.');
  end if;
  if exists (select 1 from public.partidas p where p.torneio_id = p_id and p.vencedor is not null) then
    perform privado.recusar('Já há resultados registrados: a chave não pode mais ser desfeita.');
  end if;

  delete from public.partidas p where p.torneio_id = p_id;
  update public.torneio_inscritos i set grupo = null where i.torneio_id = p_id and i.grupo is not null;
  update public.torneios t set situacao = 'inscricoes' where t.id = p_id;
  return p_id;
end;
$$;

