-- Menor chave (2, 4, 8, 16...) em que cabem os inscritos.
create function privado.tamanho_da_chave(p_quantidade integer)
returns integer
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_tamanho integer := 1;
begin
  while v_tamanho < p_quantidade loop
    v_tamanho := v_tamanho * 2;
  end loop;
  return v_tamanho;
end;
$$;

-- Numero de cabeca de chave de cada vaga, de cima para baixo.
-- 8 -> {1,8,5,4,3,6,7,2}: o 1 no topo, o 2 na base, estreia contra o espelhado.
create function privado.ordem_dos_cabecas(p_tamanho integer)
returns integer[]
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_ordem integer[] := array[1];
  v_nova integer[];
  v_soma integer;
begin
  while cardinality(v_ordem) < p_tamanho loop
    v_soma := cardinality(v_ordem) * 2 + 1;
    v_nova := '{}';
    for i in 1..cardinality(v_ordem) loop
      if (i - 1) % 2 = 0 then
        v_nova := v_nova || v_ordem[i] || (v_soma - v_ordem[i]);
      else
        v_nova := v_nova || (v_soma - v_ordem[i]) || v_ordem[i];
      end if;
    end loop;
    v_ordem := v_nova;
  end loop;
  return v_ordem;
end;
$$;

-- Em que rodada duas vagas (contadas a partir de 0) se encontrariam.
create function privado.rodada_do_encontro(p_vaga_a integer, p_vaga_b integer)
returns integer
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_diferenca integer := p_vaga_a # p_vaga_b;
  v_rodada integer := 0;
begin
  while v_diferenca > 0 loop
    v_rodada := v_rodada + 1;
    v_diferenca := v_diferenca >> 1;
  end loop;
  return v_rodada;
end;
$$;

-- "Final", "Semifinal", "Quartas de final"... pela distancia ate a final.
create function privado.nome_da_fase(p_rodada integer, p_total integer)
returns text
language sql
immutable
set search_path = ''
as $$
  select case p_total - p_rodada
    when 0 then 'Final'
    when 1 then 'Semifinal'
    when 2 then 'Quartas de final'
    when 3 then 'Oitavas de final'
    else p_rodada || 'ª rodada'
  end;
$$;

-- Tamanho de cada grupo (de 3 ou 4): 7 -> {4,3}.
create function privado.tamanhos_dos_grupos(p_quantidade integer)
returns integer[]
language sql
immutable
set search_path = ''
as $$
  with g as (select ceil(p_quantidade / 4.0)::int as grupos)
  select array_agg(p_quantidade / g.grupos + (i < p_quantidade % g.grupos)::int order by i)
  from g, generate_series(0, g.grupos - 1) as i;
$$;

-- Recusa a geracao da chave quando a quantidade de inscricoes nao serve para
-- o formato (mesmas mensagens de `previaDaChave`).
create function privado.validar_previa_da_chave(
  p_formato text, p_quantidade integer, p_classificados integer)
returns void
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_menor integer;
begin
  if p_quantidade > 64 then
    perform privado.recusar('O limite é de 64 inscrições por torneio.');
  end if;
  if p_formato = 'eliminatoria' then
    if p_quantidade < 2 then
      perform privado.recusar('A eliminatória precisa de pelo menos 2 inscrições.');
    end if;
  elsif p_formato = 'todos_contra_todos' then
    if p_quantidade < 3 then
      perform privado.recusar('Todos contra todos precisa de pelo menos 3 inscrições.');
    end if;
  else
    if p_quantidade < 6 then
      perform privado.recusar(
        'Grupos + eliminatória precisa de pelo menos 6 inscrições (dois grupos de 3).');
    end if;
    select min(t) into v_menor from unnest(privado.tamanhos_dos_grupos(p_quantidade)) as t;
    if p_classificados < 1 or p_classificados >= v_menor then
      perform privado.recusar(format(
        'Passam %s por grupo (Configurações), mas o menor grupo teria %s inscrições. Ajuste as inscrições ou as Configurações.',
        p_classificados, v_menor));
    end if;
  end if;
end;
$$;

-- Partidas de uma eliminatoria a partir das vagas (de cima para baixo; vaga
-- vazia = folga). Nao grava: devolve as linhas para quem chamou inserir.
-- Ids `<prefixo>-r<rodada>-<ordem>`. A folga da 1a rodada nao vira partida:
-- quem a recebe ja nasce na partida da 2a rodada (`montarEliminatoria`).
create function privado.linhas_da_eliminatoria(
  p_torneio public.torneios, p_vagas text[], p_prefixo text)
returns setof public.partidas
language plpgsql
stable
set search_path = ''
as $$
declare
  v_n integer := cardinality(p_vagas);
  v_total integer := 0;
  v_linhas public.partidas[] := '{}';
  v_ids text[] := '{}';
  v_p public.partidas;
  v_pos integer;
  v_indice integer;
  v_lado text;
  v_alunos text[];
begin
  while (1 << v_total) < v_n loop
    v_total := v_total + 1;
  end loop;

  for v_rodada in 1..v_total loop
    for v_i in 0..(v_n >> v_rodada) - 1 loop
      continue when v_rodada = 1
        and (p_vagas[2 * v_i + 1] is null or p_vagas[2 * v_i + 2] is null);
      v_p := null;
      v_p.id := format('%s-r%s-%s', p_prefixo, v_rodada, v_i + 1);
      v_p.torneio_id := p_torneio.id;
      v_p.data := p_torneio.data;
      v_p.lado_a := '{}';
      v_p.lado_b := '{}';
      v_p.wo := false;
      v_p.fase := privado.nome_da_fase(v_rodada, v_total);
      v_p.rodada := v_rodada;
      v_p.ordem := v_i + 1;
      if v_rodada < v_total then
        v_p.proxima_partida_id := format('%s-r%s-%s', p_prefixo, v_rodada + 1, v_i / 2 + 1);
        v_p.lado_na_proxima := case when v_i % 2 = 0 then 'A' else 'B' end;
      end if;
      v_p.criado_em := now();
      v_linhas := v_linhas || v_p;
      v_ids := v_ids || v_p.id;
    end loop;
  end loop;

  for v_vaga in 0..v_n - 1 loop
    continue when p_vagas[v_vaga + 1] is null;
    select i.alunos_ids into v_alunos from public.torneio_inscritos i where i.id = p_vagas[v_vaga + 1];
    v_indice := v_vaga / 2;
    v_pos := array_position(v_ids, format('%s-r1-%s', p_prefixo, v_indice + 1));
    v_lado := case when v_vaga % 2 = 0 then 'A' else 'B' end;
    if v_pos is null then
      -- Folga: entra direto na partida da 2a rodada.
      v_pos := array_position(v_ids, format('%s-r2-%s', p_prefixo, v_indice / 2 + 1));
      v_lado := case when v_indice % 2 = 0 then 'A' else 'B' end;
    end if;
    continue when v_pos is null;
    v_p := v_linhas[v_pos];
    if v_lado = 'A' then
      v_p.inscricao_a_id := p_vagas[v_vaga + 1];
      v_p.lado_a := v_alunos;
    else
      v_p.inscricao_b_id := p_vagas[v_vaga + 1];
      v_p.lado_b := v_alunos;
    end if;
    v_linhas[v_pos] := v_p;
  end loop;

  return query select * from unnest(v_linhas);
end;
$$;

-- Partidas do todos contra todos pelo "metodo do circulo" (cada um joga no
-- maximo uma vez por rodada; com numero impar, um fica de folga por rodada).
-- Com `p_grupo`, sao os jogos de um grupo ("Grupo A", ids `<prefixo>-gA-r1-1`).
create function privado.linhas_todos_contra_todos(
  p_torneio public.torneios, p_membros text[], p_prefixo text, p_grupo text)
returns setof public.partidas
language plpgsql
stable
set search_path = ''
as $$
declare
  v_roda text[] := p_membros;
  v_len integer;
  v_jogo integer;
  v_a text;
  v_b text;
  v_p public.partidas;
begin
  if cardinality(p_membros) % 2 = 1 then
    v_roda := v_roda || null::text;
  end if;
  v_len := cardinality(v_roda);

  for v_r in 0..v_len - 2 loop
    v_jogo := 0;
    for v_i in 0..v_len / 2 - 1 loop
      v_a := v_roda[v_i + 1];
      v_b := v_roda[v_len - v_i];
      continue when v_a is null or v_b is null;
      v_jogo := v_jogo + 1;
      v_p := null;
      v_p.id := format('%s-%sr%s-%s', p_prefixo,
        case when p_grupo is null then '' else 'g' || p_grupo || '-' end, v_r + 1, v_jogo);
      v_p.torneio_id := p_torneio.id;
      v_p.data := p_torneio.data;
      v_p.inscricao_a_id := v_a;
      v_p.inscricao_b_id := v_b;
      select i.alunos_ids into v_p.lado_a from public.torneio_inscritos i where i.id = v_a;
      select i.alunos_ids into v_p.lado_b from public.torneio_inscritos i where i.id = v_b;
      v_p.wo := false;
      v_p.fase := case when p_grupo is null then 'Rodada ' || (v_r + 1) else 'Grupo ' || p_grupo end;
      v_p.grupo := p_grupo;
      v_p.rodada := v_r + 1;
      v_p.ordem := v_jogo;
      v_p.criado_em := now();
      return next v_p;
    end loop;
    -- O primeiro fica parado; os demais giram uma casa.
    v_roda := v_roda[1:1] || v_roda[v_len:v_len] || v_roda[2:v_len - 1];
  end loop;
end;
$$;

-- ---------------------------------------------------------------------------
-- 3. Classificacao com desempate (H8)
-- ---------------------------------------------------------------------------

-- Ordena aplicando os criterios na ordem das Configuracoes. Quando um criterio
-- separa os empatados em blocos, cada bloco que continua empatado recomeca da
-- lista (o confronto direto e refeito so entre quem ainda empata). Devolve os
-- ids na ordem final e o criterio que decidiu (null = o do nivel de cima).
create function privado.desempatar(
  p_ids text[], p_criterios text[], p_estatisticas jsonb, p_jogos jsonb, p_em_empate boolean)
returns table (inscricao_id text, motivo text)
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_nome text;
  v_valor jsonb;
  v_distintos numeric[];
  v_v numeric;
  v_bloco text[];
  v_motivo text;
begin
  if coalesce(cardinality(p_ids), 0) <= 1 then
    return query select u.id, null::text from unnest(p_ids) as u(id);
    return;
  end if;

  for v_c in 1..coalesce(cardinality(p_criterios), 0) loop
    v_nome := translate(lower(p_criterios[v_c]),
      'áàâãäéèêëíìîïóòôõöúùûüç', 'aaaaaeeeeiiiiooooouuuuc');
    if v_nome like '%vitoria%' then
      select jsonb_object_agg(u.id, (p_estatisticas -> u.id ->> 'vitorias')::numeric)
        into v_valor from unnest(p_ids) as u(id);
    elsif v_nome like '%set%' then
      select jsonb_object_agg(u.id, (p_estatisticas -> u.id ->> 'sets_pro')::numeric
                                  - (p_estatisticas -> u.id ->> 'sets_contra')::numeric)
        into v_valor from unnest(p_ids) as u(id);
    elsif v_nome like '%game%' then
      select jsonb_object_agg(u.id, (p_estatisticas -> u.id ->> 'games_pro')::numeric
                                  - (p_estatisticas -> u.id ->> 'games_contra')::numeric)
        into v_valor from unnest(p_ids) as u(id);
    elsif v_nome like '%confronto%' then
      -- Vitorias so nos jogos entre os que estao empatados.
      select jsonb_object_agg(u.id, (
          select count(*) from jsonb_array_elements(p_jogos) as j(jogo)
           where j.jogo ->> 'a' = any (p_ids) and j.jogo ->> 'b' = any (p_ids)
             and j.jogo ->> 'vencedor' = u.id))
        into v_valor from unnest(p_ids) as u(id);
    else
      continue;  -- texto desconhecido e ignorado
    end if;

    select array_agg(d.v order by d.v desc) into v_distintos
      from (select distinct (v_valor ->> u.id)::numeric as v from unnest(p_ids) as u(id)) as d;
    continue when cardinality(v_distintos) = 1;

    v_motivo := case when p_em_empate or v_c > 1 then p_criterios[v_c] end;
    foreach v_v in array v_distintos loop
      select array_agg(u.id order by u.n) into v_bloco
        from unnest(p_ids) with ordinality as u(id, n)
       where (v_valor ->> u.id)::numeric = v_v;
      return query
        select d.inscricao_id, coalesce(d.motivo, v_motivo)
          from privado.desempatar(v_bloco, p_criterios, p_estatisticas, p_jogos, true) as d;
    end loop;
    return;
  end loop;

  -- Nada separou: ficam na ordem recebida (cabeca de chave, depois inscricao).
  return query
    select u.id, 'Cabeça de chave e ordem de inscrição'::text
      from unnest(p_ids) with ordinality as u(id, n) order by u.n;
end;
$$;

-- Classificacao de um grupo (ou do todos contra todos, com p_grupo null) pelas
-- partidas com resultado, com os criterios das Configuracoes (`classificar`).
create function privado.classificar(p_torneio_id text, p_grupo text)
returns table (
  inscricao_id text, posicao integer, jogos integer, vitorias integer, derrotas integer,
  sets_pro integer, sets_contra integer, games_pro integer, games_contra integer, desempate text)
language plpgsql
stable
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_ids text[];
  v_estatisticas jsonb;
  v_jogos jsonb;
  v_criterios text[];
begin
  select array_agg(i.id order by i.cabeca_de_chave nulls last, i.ordem_inscricao)
    into v_ids
    from public.torneio_inscritos i
   where i.torneio_id = p_torneio_id and (p_grupo is null or i.grupo = p_grupo);
  if v_ids is null then
    return;
  end if;
  select array(select jsonb_array_elements_text(c.criterios_desempate))
    into v_criterios from public.configuracoes c where c.id = 1;

  -- Partidas com resultado entre os participantes, com sets e games.
  select coalesce(jsonb_agg(jsonb_build_object(
           'a', p.inscricao_a_id,
           'b', p.inscricao_b_id,
           'lado', p.vencedor,
           'vencedor', case p.vencedor when 'A' then p.inscricao_a_id else p.inscricao_b_id end,
           'sa', t.sets_a, 'sb', t.sets_b, 'ga', t.games_a, 'gb', t.games_b)), '[]')
    into v_jogos
    from public.partidas p
    cross join lateral privado.totais_da_partida(p.placar, p.vencedor, p.wo) as t
   where p.torneio_id = p_torneio_id
     and (p_grupo is null or p.grupo = p_grupo)
     and p.vencedor is not null
     and p.inscricao_a_id = any (v_ids) and p.inscricao_b_id = any (v_ids);

  with j as (
    select x ->> 'a' as a, x ->> 'b' as b, x ->> 'lado' as lado,
           (x ->> 'sa')::int as sa, (x ->> 'sb')::int as sb,
           (x ->> 'ga')::int as ga, (x ->> 'gb')::int as gb
      from jsonb_array_elements(v_jogos) as e(x)
  ),
  l as (
    select j.a as id, (j.lado = 'A')::int as v, (j.lado = 'B')::int as d,
           j.sa as sp, j.sb as sc, j.ga as gp, j.gb as gc
      from j
    union all
    select j.b, (j.lado = 'B')::int, (j.lado = 'A')::int, j.sb, j.sa, j.gb, j.ga
      from j
  ),
  e as (
    select u.id,
           count(l.id)::int as jogos,
           coalesce(sum(l.v), 0)::int as vitorias,
           coalesce(sum(l.d), 0)::int as derrotas,
           coalesce(sum(l.sp), 0)::int as sets_pro,
           coalesce(sum(l.sc), 0)::int as sets_contra,
           coalesce(sum(l.gp), 0)::int as games_pro,
           coalesce(sum(l.gc), 0)::int as games_contra
      from unnest(v_ids) as u(id)
      left join l on l.id = u.id
     group by u.id
  )
  select jsonb_object_agg(e.id, to_jsonb(e)) into v_estatisticas from e;

  return query
    select d.inscricao_id,
           d.n::int,
           (v_estatisticas -> d.inscricao_id ->> 'jogos')::int,
           (v_estatisticas -> d.inscricao_id ->> 'vitorias')::int,
           (v_estatisticas -> d.inscricao_id ->> 'derrotas')::int,
           (v_estatisticas -> d.inscricao_id ->> 'sets_pro')::int,
           (v_estatisticas -> d.inscricao_id ->> 'sets_contra')::int,
           (v_estatisticas -> d.inscricao_id ->> 'games_pro')::int,
           (v_estatisticas -> d.inscricao_id ->> 'games_contra')::int,
           case when (v_estatisticas -> d.inscricao_id ->> 'jogos')::int > 0 then d.motivo end
      from privado.desempatar(v_ids, v_criterios, v_estatisticas, v_jogos, false)
           with ordinality as d(inscricao_id, motivo, n)
     order by d.n;
end;
$$;

