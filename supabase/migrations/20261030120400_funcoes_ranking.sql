-- Le o placar digitado ("6/4 3/6 10/8", "6x4 6-2", "7/6(5)").
-- Devolve [{a, b, tb}] ou null se nao for um placar.
create function privado.ler_placar(p_texto text)
returns jsonb
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_pedacos text[] := '{}';
  v_pedaco text;
  v_partes text[];
  v_sets jsonb := '[]';
begin
  for v_pedaco in
    select x from regexp_split_to_table(
      regexp_replace(coalesce(p_texto, ''), '^\s+|\s+$', '', 'g'), '[\s,;]+') as x
  loop
    continue when v_pedaco = '';
    -- "7/6 (5)": o tie-break escrito separado volta para o set anterior.
    if left(v_pedaco, 1) = '(' and cardinality(v_pedacos) > 0 then
      v_pedacos[cardinality(v_pedacos)] := v_pedacos[cardinality(v_pedacos)] || v_pedaco;
    else
      v_pedacos := v_pedacos || v_pedaco;
    end if;
  end loop;
  if cardinality(v_pedacos) = 0 or cardinality(v_pedacos) > 5 then
    return null;
  end if;

  foreach v_pedaco in array v_pedacos loop
    v_partes := regexp_match(v_pedaco, '^(\d{1,2})[/xX-](\d{1,2})(?:\((\d{1,2})\))?$');
    if v_partes is null then
      return null;
    end if;
    v_sets := v_sets || jsonb_build_object(
      'a', v_partes[1]::int, 'b', v_partes[2]::int, 'tb', v_partes[3]::int);
  end loop;
  return v_sets;
end;
$$;

-- "6/4 3/6 10/8" a partir dos sets lidos.
create function privado.escrever_placar(p_sets jsonb)
returns text
language sql
immutable
set search_path = ''
as $$
  select string_agg(
    format('%s/%s', s ->> 'a', s ->> 'b') || coalesce('(' || (s ->> 'tb') || ')', ''),
    ' ' order by n)
  from jsonb_array_elements(p_sets) with ordinality as e(s, n);
$$;

-- Confere se o placar combina com o vencedor e devolve o placar arrumado
-- ("W.O." na vitoria por W.O.). Mesmas mensagens de `validarResultado`.
create function privado.validar_resultado(
  p_placar text, p_vencedor text, p_wo boolean, p_nome_a text, p_nome_b text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_texto text := regexp_replace(coalesce(p_placar, ''), '^\s+|\s+$', '', 'g');
  v_sets jsonb;
  v_set jsonb;
  v_sets_a integer;
  v_sets_b integer;
  v_pela_contagem text;
  v_ultimo jsonb;
begin
  if p_vencedor is null or p_vencedor not in ('A', 'B') then
    perform privado.recusar('Escolha quem venceu a partida.');
  end if;
  if coalesce(p_wo, false) then
    return 'W.O.';
  end if;
  if v_texto = '' then
    perform privado.recusar('Informe o placar (ex.: 6/4 3/6 10/8) ou marque W.O.');
  end if;
  v_sets := privado.ler_placar(v_texto);
  if v_sets is null then
    perform privado.recusar(format(
      'Placar "%s" não reconhecido. Escreva os sets separados por espaço, como 6/4 3/6 10/8.', v_texto));
  end if;

  select s into v_set
    from jsonb_array_elements(v_sets) with ordinality as e(s, n)
   where (s ->> 'a')::int = (s ->> 'b')::int
   order by n limit 1;
  if v_set is not null then
    perform privado.recusar(format(
      'Um set não termina empatado (%s/%s). Confira o placar.', v_set ->> 'a', v_set ->> 'b'));
  end if;

  select count(*) filter (where (s ->> 'a')::int > (s ->> 'b')::int),
         count(*) filter (where (s ->> 'a')::int < (s ->> 'b')::int)
    into v_sets_a, v_sets_b
    from jsonb_array_elements(v_sets) as e(s);
  if v_sets_a = v_sets_b then
    perform privado.recusar(format(
      'O placar está empatado em sets (%s a %s). Falta o set decisivo?', v_sets_a, v_sets_b));
  end if;
  v_pela_contagem := case when v_sets_a > v_sets_b then 'A' else 'B' end;
  if v_pela_contagem <> p_vencedor then
    perform privado.recusar(format(
      'O placar não bate com o vencedor: por esse placar quem venceu foi %s.',
      case v_pela_contagem when 'A' then p_nome_a else p_nome_b end));
  end if;
  v_ultimo := v_sets -> (jsonb_array_length(v_sets) - 1);
  if (case when (v_ultimo ->> 'a')::int > (v_ultimo ->> 'b')::int then 'A' else 'B' end) <> p_vencedor then
    perform privado.recusar(
      'O último set precisa ser de quem venceu a partida. Confira a ordem dos sets.');
  end if;
  return privado.escrever_placar(v_sets);
end;
$$;

-- Sets e games de cada lado (saldo da classificacao). W.O. conta como
-- 6/0 6/0 para quem venceu (H8); super tie-break (10/8) conta como 1 game.
create function privado.totais_da_partida(
  p_placar text, p_vencedor text, p_wo boolean,
  out sets_a integer, out sets_b integer, out games_a integer, out games_b integer)
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_set jsonb;
  v_a integer;
  v_b integer;
  v_super boolean;
begin
  sets_a := 0; sets_b := 0; games_a := 0; games_b := 0;
  if p_vencedor is null then
    return;
  end if;
  if coalesce(p_wo, false) then
    if p_vencedor = 'A' then
      sets_a := 2; games_a := 12;
    else
      sets_b := 2; games_b := 12;
    end if;
    return;
  end if;
  for v_set in select s from jsonb_array_elements(coalesce(privado.ler_placar(p_placar), '[]')) as e(s) loop
    v_a := (v_set ->> 'a')::int;
    v_b := (v_set ->> 'b')::int;
    v_super := greatest(v_a, v_b) >= 10;
    if v_a > v_b then
      sets_a := sets_a + 1;
    else
      sets_b := sets_b + 1;
    end if;
    games_a := games_a + case when v_super then (v_a > v_b)::int else v_a end;
    games_b := games_b + case when v_super then (v_a < v_b)::int else v_b end;
  end loop;
end;
$$;

-- Nome de um lado da partida, para as mensagens ("Ana", "Ana / Bia").
create function privado.nome_do_lado(p_alunos_ids text[])
returns text
language sql
stable
set search_path = ''
as $$
  select coalesce(
    nullif(string_agg(coalesce(a.nome, '?'), ' / ' order by u.n), ''), '?')
  from unnest(p_alunos_ids) with ordinality as u(id, n)
  left join public.alunos a on a.id = u.id;
$$;

