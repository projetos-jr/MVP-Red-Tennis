-- Recusa a reserva se a quadra ja estiver ocupada, dizendo quem ocupa
-- (`garantirQuadraLivre`). A exclusion constraint de `ocupacoes` continua
-- valendo; aqui so se troca o erro generico por uma mensagem clara.
create function privado.ranking_garantir_quadra_livre(
  p_quadra_id text, p_data date, p_hora_inicio time, p_hora_fim time)
returns void
language plpgsql
stable
set search_path = ''
as $$
declare
  v_ocupacao public.ocupacoes;
  v_nomes text[];
  v_descricao text;
begin
  select * into v_ocupacao from public.ocupacoes o
   where o.quadra_id = p_quadra_id and o.data = p_data and o.situacao <> 'cancelada'
     and o.hora_inicio < p_hora_fim and p_hora_inicio < o.hora_fim
   order by o.hora_inicio
   limit 1;
  if not found then
    return;
  end if;
  if v_ocupacao.tipo = 'Bloqueio' then
    v_descricao := 'Bloqueio' || coalesce(' · ' || nullif(v_ocupacao.descricao, ''), '');
  else
    select coalesce(array_agg(a.nome order by a.nome), '{}') into v_nomes
      from public.ocupacao_alunos oa join public.alunos a on a.id = oa.aluno_id
     where oa.ocupacao_id = v_ocupacao.id;
    v_descricao := v_ocupacao.tipo || case
      when cardinality(v_nomes) = 0 then ''
      when cardinality(v_nomes) <= 2 then ' · ' || array_to_string(v_nomes, ' e ')
      else format(' · %s e mais %s', v_nomes[1], cardinality(v_nomes) - 1)
    end;
  end if;
  perform privado.recusar(format('%s já está ocupada em %s das %s às %s (%s).',
    case when p_quadra_id = 'paredao' then 'Paredão' else 'Quadra ' || p_quadra_id end,
    to_char(p_data, 'DD/MM'),
    to_char(v_ocupacao.hora_inicio, 'HH24:MI'),
    to_char(v_ocupacao.hora_fim, 'HH24:MI'),
    v_descricao));
end;
$$;

-- Confere as inscricoes ([{alunosIds, cabecaDeChave}], como vem da tela):
-- um aluno (simples) ou dois diferentes (duplas), alunos ativos, ninguem em
-- duas inscricoes, cabecas numerados 1, 2, 3... (`validarInscricoes`).
create function privado.validar_inscricoes(p_duplas boolean, p_inscricoes jsonb)
returns void
language plpgsql
stable
set search_path = ''
as $$
declare
  v_inscricao jsonb;
  v_alunos text[];
  v_aluno_id text;
  v_aluno public.alunos;
  v_vistos text[] := '{}';
  v_cabecas numeric[];
begin
  if jsonb_array_length(coalesce(p_inscricoes, '[]')) > 64 then
    perform privado.recusar('O limite é de 64 inscrições por torneio.');
  end if;
  for v_inscricao in select value from jsonb_array_elements(coalesce(p_inscricoes, '[]')) loop
    v_alunos := array(select jsonb_array_elements_text(coalesce(v_inscricao -> 'alunosIds', '[]')));
    if cardinality(v_alunos) <> (case when p_duplas then 2 else 1 end) then
      perform privado.recusar(case when p_duplas
        then 'Cada inscrição de duplas precisa de dois jogadores.'
        else 'Cada inscrição de simples tem um jogador só.' end);
    end if;
    if p_duplas and v_alunos[1] = v_alunos[2] then
      perform privado.recusar('Uma dupla precisa de dois jogadores diferentes.');
    end if;
    foreach v_aluno_id in array v_alunos loop
      select * into v_aluno from public.alunos a where a.id = v_aluno_id;
      if not found then
        perform privado.recusar('Aluno não encontrado.');
      end if;
      if not v_aluno.ativo then
        perform privado.recusar(format(
          '%s não está ativo na arena e não pode se inscrever.', v_aluno.nome));
      end if;
      if v_aluno_id = any (v_vistos) then
        perform privado.recusar(format('%s aparece em duas inscrições.', v_aluno.nome));
      end if;
      v_vistos := v_vistos || v_aluno_id;
    end loop;
  end loop;

  select array_agg((e.i ->> 'cabecaDeChave')::numeric order by (e.i ->> 'cabecaDeChave')::numeric)
    into v_cabecas
    from jsonb_array_elements(coalesce(p_inscricoes, '[]')) as e(i)
   where e.i ->> 'cabecaDeChave' is not null;
  if v_cabecas is not null
     and v_cabecas <> array(select generate_series(1, cardinality(v_cabecas))::numeric) then
    perform privado.recusar(
      'Numere os cabeças de chave em sequência (1, 2, 3…), sem repetir nem pular.');
  end if;
end;
$$;

