-- Registrar ou corrigir o resultado de uma partida de ranking.
create function privado.gravar_resultado_de_ranking(
  p_id text, p_placar text, p_vencedor text, p_wo boolean, p_data date, p_correcao boolean)
returns text
language plpgsql
set search_path = ''
as $$
declare
  v_partida public.partidas;
  v_reserva public.ocupacoes;
  v_data date;
  v_placar text;
begin
  select * into v_partida from public.partidas p where p.id = p_id for update;
  if not found then
    perform privado.recusar('Partida não encontrada.');
  end if;
  if v_partida.torneio_id is not null then
    perform privado.recusar('O resultado de partida de torneio é registrado na chave do torneio.');
  end if;
  if p_correcao and v_partida.vencedor is null then
    perform privado.recusar('Esta partida ainda não tem resultado.');
  end if;
  if not p_correcao and v_partida.vencedor is not null then
    perform privado.recusar('Esta partida já tem resultado: use a correção.');
  end if;

  -- Partida com reserva de quadra fica na data da reserva.
  if v_partida.ocupacao_id is not null then
    select * into v_reserva from public.ocupacoes o where o.id = v_partida.ocupacao_id;
  end if;
  v_data := case when v_reserva.id is not null then v_reserva.data
                 else coalesce(p_data, v_partida.data) end;
  if v_data is null then
    perform privado.recusar('Informe a data da partida.');
  end if;
  if v_data > privado.hoje() then
    perform privado.recusar(case when v_reserva.id is not null
      then format('A partida está marcada para %s: o resultado entra a partir desse dia.',
                  to_char(v_data, 'DD/MM/YYYY'))
      else 'A data da partida não pode ser depois de hoje.' end);
  end if;
  v_placar := privado.validar_resultado(p_placar, p_vencedor, p_wo,
    privado.nome_do_lado(v_partida.lado_a), privado.nome_do_lado(v_partida.lado_b));

  update public.partidas p
     set data = v_data, placar = v_placar, vencedor = p_vencedor, wo = coalesce(p_wo, false)
   where p.id = p_id;
  return p_id;
end;
$$;

-- Torneio da partida, travado (para dois balcoes nao mexerem na mesma chave ao
