-- ============================================================================
--  Funcoes do ranking e dos torneios (chaveamento)
-- ============================================================================
--  Leva para o Postgres as operacoes de `src/lib/banco/operacoes/ranking.ts` e
--  as regras de `src/lib/banco/regras/ranking.ts` (placar, pontuacao) e
--  `src/lib/banco/regras/torneios.ts` (geracao da chave, avanco do vencedor,
--  classificacao dos grupos). A tela passa a chamar `supabase.rpc(...)`.
--
--  O avanco de chave e regra critica: gravar um resultado leva o vencedor para
--  a partida seguinte (`proxima_partida_id`, `lado_na_proxima`) dentro da mesma
--  transacao, e a fase eliminatoria do formato de grupos e montada pelo banco
--  quando o ultimo jogo dos grupos termina.
--
--  A chave gerada aqui tem EXATAMENTE a mesma estrutura da do front (mesmos
--  cabecas de chave e folgas, mesmos nomes de fase, rodada e ordem, mesmo
--  padrao de id `<prefixo>-r<rodada>-<ordem>`). O unico ponto que nao se
--  repete e o sorteio de quem nao e cabeca de chave: o front sorteia com uma
--  semente propria; aqui a tela pode mandar a ordem sorteada (`p_sorteio`) ou
--  deixar o banco sortear com random().
--
--  Mudanca de schema: `torneio_inscritos.ordem_inscricao`. O desempate final
--  da classificacao ("Cabeca de chave e ordem de inscricao") usa a ordem em
--  que as inscricoes foram feitas, que no front e a posicao na lista e no
--  banco nao existia (os ids sao aleatorios).
--
--  Pontuacao do ranking: so leitura, entao virou a funcao `ranking_em(data)`
--  (a tela precisa do ranking de hoje e do de 7 dias atras) e a view
--  `ranking` (o de hoje), ambas com as permissoes de quem consulta.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 0. Schema: ordem das inscricoes
-- ---------------------------------------------------------------------------
-- Numero crescente: inscricao nova vai para o fim, como na lista da tela.
alter table public.torneio_inscritos
  add column ordem_inscricao bigint generated by default as identity;
create index torneio_inscritos_ordem_idx on public.torneio_inscritos (torneio_id, ordem_inscricao);

