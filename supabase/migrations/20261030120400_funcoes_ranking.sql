-- Corrige um resultado, so enquanto a partida seguinte nao foi jogada (nos
-- grupos, enquanto a eliminatoria nao comecou). O novo vencedor toma o lugar
-- do antigo na partida seguinte.
create function public.corrigir_resultado_de_torneio(
  p_partida_id text, p_placar text default null, p_vencedor text default null,
  p_wo boolean default false, p_data date default null)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
begin
  perform privado.iniciar_operacao('Corrigir resultado de torneio', 'ranking');
  return privado.gravar_resultado_de_torneio(p_partida_id, p_placar, p_vencedor, p_wo, p_data, true);
end;
$$;

-- Apaga um resultado lancado por engano (mesmas condicoes da correcao) e tira
-- o vencedor da partida seguinte.
create function public.apagar_resultado_de_torneio(p_partida_id text)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_partida public.partidas;
  v_torneio public.torneios;
  v_bloqueio text;
begin
  perform privado.iniciar_operacao('Apagar resultado de torneio', 'ranking');
  v_torneio := privado.torneio_da_partida(p_partida_id);
  select * into v_partida from public.partidas p where p.id = p_partida_id for update;
  v_bloqueio := privado.bloqueio_de_correcao(v_partida);
  if v_bloqueio is not null then
    perform privado.recusar(v_bloqueio);
  end if;
  if v_partida.vencedor is null then
    perform privado.recusar('Esta partida ainda não tem resultado.');
  end if;

  update public.partidas p set placar = null, vencedor = null, wo = false where p.id = v_partida.id;
  if v_partida.proxima_partida_id is not null and v_partida.lado_na_proxima is not null then
    perform privado.levar_para_seguinte(
      v_partida.proxima_partida_id, v_partida.lado_na_proxima, null, null);
  end if;

  if v_partida.grupo is not null then
    perform privado.atualizar_fase_eliminatoria(v_torneio.id);
  end if;
  return jsonb_build_object(
    'torneioId', v_torneio.id,
    'situacao', privado.atualizar_situacao_do_torneio(v_torneio.id));
end;
$$;

