-- Registrar ou corrigir o resultado de uma partida de torneio e levar o
-- vencedor para a seguinte (`gravarResultadoDeTorneio` + `aplicarResultado`).
create function privado.gravar_resultado_de_torneio(
  p_partida_id text, p_placar text, p_vencedor text, p_wo boolean, p_data date, p_correcao boolean)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_partida public.partidas;
  v_torneio public.torneios;
  v_bloqueio text;
  v_data date;
  v_placar text;
begin
  v_torneio := privado.torneio_da_partida(p_partida_id);
  select * into v_partida from public.partidas p where p.id = p_partida_id for update;
  if p_correcao and v_partida.vencedor is null then
    perform privado.recusar('Esta partida ainda não tem resultado.');
  end if;
  if not p_correcao and v_partida.vencedor is not null then
    perform privado.recusar('Esta partida já tem resultado: use a correção.');
  end if;
  v_bloqueio := privado.bloqueio_de_correcao(v_partida);
  if v_bloqueio is not null then
    perform privado.recusar(v_bloqueio);
  end if;
  if v_partida.inscricao_a_id is null or v_partida.inscricao_b_id is null then
    perform privado.recusar('Esta partida ainda espera o vencedor da rodada anterior.');
  end if;

  v_data := coalesce(p_data,
    case when v_partida.data is not null and v_partida.data <= privado.hoje()
         then v_partida.data else privado.hoje() end);
  if v_data > privado.hoje() then
    perform privado.recusar('A data da partida não pode ser depois de hoje.');
  end if;
  v_placar := privado.validar_resultado(p_placar, p_vencedor, p_wo,
    privado.nome_do_lado(v_partida.lado_a), privado.nome_do_lado(v_partida.lado_b));

  update public.partidas p
     set placar = v_placar, vencedor = p_vencedor, wo = coalesce(p_wo, false), data = v_data
   where p.id = v_partida.id;
  if v_partida.proxima_partida_id is not null and v_partida.lado_na_proxima is not null then
    perform privado.levar_para_seguinte(
      v_partida.proxima_partida_id, v_partida.lado_na_proxima,
      case p_vencedor when 'A' then v_partida.inscricao_a_id else v_partida.inscricao_b_id end,
      case p_vencedor when 'A' then v_partida.lado_a else v_partida.lado_b end);
  end if;

  if v_partida.grupo is not null then
    perform privado.atualizar_fase_eliminatoria(v_torneio.id);
  end if;
  return jsonb_build_object(
    'torneioId', v_torneio.id,
    'situacao', privado.atualizar_situacao_do_torneio(v_torneio.id));
end;
$$;

