-- Partida de ranking marcada para hoje ou depois. Com `p_reserva`
-- ({"quadraId", "horaInicio", "horaFim"}), cria a ocupacao "Ranking" com os
-- dois jogadores e a liga a partida (sem cobranca). Devolve o id da partida.
create function public.marcar_partida(
  p_jogador_a text, p_jogador_b text, p_data date, p_reserva jsonb default null)
returns text
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_a public.alunos;
  v_b public.alunos;
  v_quadra text;
  v_inicio time;
  v_fim time;
  v_ocupacao_id text;
  v_id text;
begin
  perform privado.iniciar_operacao('Marcar partida de ranking', 'ranking');
  v_a := privado.jogador_do_ranking(p_jogador_a, 'jogador A');
  v_b := privado.jogador_do_ranking(p_jogador_b, 'jogador B');
  if v_a.id = v_b.id then
    perform privado.recusar('Escolha dois jogadores diferentes.');
  end if;
  if p_data is null then
    perform privado.recusar('Informe a data da partida.');
  end if;
  if p_data < privado.hoje() then
    perform privado.recusar(
      'Essa data já passou: para uma partida que já aconteceu, registre o resultado.');
  end if;

  if p_reserva is not null and jsonb_typeof(p_reserva) = 'object' then
    -- A reserva grava na agenda: confere tambem a permissao da agenda.
    perform privado.iniciar_operacao('Marcar partida de ranking', 'agenda');
    v_quadra := p_reserva ->> 'quadraId';
    v_inicio := nullif(p_reserva ->> 'horaInicio', '')::time;
    v_fim := nullif(p_reserva ->> 'horaFim', '')::time;
    if v_quadra = 'paredao' then
      perform privado.recusar('O paredão não recebe partidas: escolha uma das quadras 1 a 4.');
    end if;
    if v_inicio is null or v_fim is null or not (v_inicio < v_fim) then
      perform privado.recusar('O horário de término precisa ser depois do início.');
    end if;
    if v_inicio < '07:00' or v_fim > '22:00' then
      perform privado.recusar('A arena funciona das 07:00 às 22:00.');
    end if;
    perform privado.ranking_garantir_quadra_livre(v_quadra, p_data, v_inicio, v_fim);

    insert into public.ocupacoes (quadra_id, data, hora_inicio, hora_fim, tipo, situacao)
    values (v_quadra, p_data, v_inicio, v_fim, 'Ranking', 'agendada')
    returning id into v_ocupacao_id;
    insert into public.ocupacao_alunos (ocupacao_id, aluno_id, presenca)
    values (v_ocupacao_id, v_a.id, 'a_marcar'), (v_ocupacao_id, v_b.id, 'a_marcar');
  end if;

  insert into public.partidas (data, lado_a, lado_b, ocupacao_id)
  values (p_data, array[v_a.id], array[v_b.id], v_ocupacao_id)
  returning id into v_id;
  return v_id;
end;
$$;

