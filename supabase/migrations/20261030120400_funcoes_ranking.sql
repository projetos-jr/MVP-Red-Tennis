-- 9. Leituras: ranking e classificacao
-- ---------------------------------------------------------------------------

-- Ranking de todos os alunos inscritos ate a data `p_ate` (inclusive; null =
-- tudo), com a pontuacao das Configuracoes (H7). Partidas de torneio so contam
-- com `torneio_conta_para_ranking`; duplas nunca contam; quem perde por W.O.
-- nao ganha os pontos de derrota. Desempate: vitorias, depois nome.
create function public.ranking_em(p_ate date default null)
returns table (
  aluno_id text, posicao integer, pontos integer, vitorias integer, derrotas integer, partidas integer)
language sql
stable
security invoker
set search_path = ''
as $$
  with cfg as (
    select c.pontos_vitoria, c.pontos_derrota, c.torneio_conta_para_ranking
      from public.configuracoes c where c.id = 1
  ),
  validas as (
    select p.lado_a[1] as a, p.lado_b[1] as b, p.vencedor, p.wo
      from public.partidas p, cfg
     where p.vencedor is not null
       and cardinality(p.lado_a) = 1 and cardinality(p.lado_b) = 1
       and (p.torneio_id is null or cfg.torneio_conta_para_ranking)
       and (p_ate is null or p.data is null or p.data <= p_ate)
  ),
  lados as (
    select case v.vencedor when 'A' then v.a else v.b end as aluno_id,
           cfg.pontos_vitoria::int as pontos, 1 as vitoria, 0 as derrota
      from validas v, cfg
    union all
    select case v.vencedor when 'A' then v.b else v.a end,
           case when v.wo then 0 else cfg.pontos_derrota::int end, 0, 1
      from validas v, cfg
  ),
  linhas as (
    select a.id, a.nome,
           coalesce(sum(l.pontos), 0)::int as pontos,
           coalesce(sum(l.vitoria), 0)::int as vitorias,
           coalesce(sum(l.derrota), 0)::int as derrotas
      from public.alunos a
      left join lados l on l.aluno_id = a.id
     where a.inscrito_ranking
     group by a.id, a.nome
  )
  select l.id,
         (row_number() over (order by l.pontos desc, l.vitorias desc, l.nome, l.id))::int,
         l.pontos, l.vitorias, l.derrotas, l.vitorias + l.derrotas
    from linhas l
   order by 2;
$$;

-- O ranking de hoje, para a tela ler com `.from('ranking')`.
create view public.ranking
with (security_invoker = true) as
select * from public.ranking_em(null);

-- Classificacao de um torneio: cada grupo (grupos + eliminatoria) ou a tabela
-- unica (todos contra todos; grupo vazio). Mesmos criterios da tela (H8).
create function public.classificacao_do_torneio(p_torneio_id text)
returns table (
  grupo text, inscricao_id text, posicao integer, jogos integer, vitorias integer,
  derrotas integer, sets_pro integer, sets_contra integer, games_pro integer,
  games_contra integer, desempate text)
language plpgsql
stable
security invoker
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_formato text;
  v_letra text;
begin
  select t.formato into v_formato from public.torneios t where t.id = p_torneio_id;
  if v_formato = 'todos_contra_todos' then
    return query select null::text, c.* from privado.classificar(p_torneio_id, null) as c;
  elsif v_formato = 'grupos_eliminatoria' then
    for v_letra in
      select distinct i.grupo from public.torneio_inscritos i
       where i.torneio_id = p_torneio_id and i.grupo is not null
       order by i.grupo
    loop
      return query select v_letra, c.* from privado.classificar(p_torneio_id, v_letra) as c;
    end loop;
  end if;
end;
$$;

